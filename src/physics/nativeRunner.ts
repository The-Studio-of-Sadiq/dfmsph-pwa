/* Run the WASI build of DFMSPH22 inside its own temporary directory */
async function runWasmEngine(inputFiles: Record<string, string>): Promise<{ exitCode: number; stdout: string; files: Record<string, string> }> {
  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), 'dfmsph22-'));
  try {
    for (const [name, content] of Object.entries(inputFiles)) {
      fs.writeFileSync(path.join(workDir, name), content, 'utf-8');
    }
    const stdoutPath = path.join(workDir, 'stdout.txt');
    const stdoutFd = fs.openSync(stdoutPath, 'w');
    let exitCode = 0;
    try {
      const wasi = new WASI({
        version: 'preview1',
        args: ['dfmsph22'],
        env: {},
        preopens: { '/': workDir },
        stdout: stdoutFd,
        stderr: stdoutFd,
        returnOnExit: true
      });
      const instance = await WebAssembly.instantiate(await getWasmModule(), wasi.getImportObject() as WebAssembly.Imports);
      exitCode = wasi.start(instance);
    } finally {
      fs.closeSync(stdoutFd);
    }

    const files: Record<string, string> = {};
    for (const name of ['OUT_U_R.c', 'out_dfmsph22.c', 'out_inp_dfm22.c', 'out_vNN_.c']) {
      const p = path.join(workDir, name);
      if (fs.existsSync(p)) files[name] = fs.readFileSync(p, 'utf-8');
    }
    return { exitCode, stdout: fs.readFileSync(stdoutPath, 'utf-8'), files };
  } finally {
    fs.rmSync(workDir, { recursive: true, force: true });
  }
}

function fallback(input: CalculationInput, log: string) {
  const tsResult = runDFMSPHCalculation(input);
  tsResult.cLogText = log;
  return { output: tsResult, isNative: false, log };
}

export async function executeNativeDFMSPH(input: CalculationInput): Promise<{ output: CalculationOutput; isNative: boolean; log: string }> {
  if (!isNativeEngineAvailable()) {
    return fallback(input, `[Native Execution Unavailable]\nengine/dfmsph22.wasm was not found. Executed calculation via TypeScript physics engine fallback.`);
  }

  const cInputText = generateInputDFMSPH22(input);
  const t0 = Date.now();
  let run: Awaited<ReturnType<typeof runWasmEngine>>;
  try {
    run = await runWasmEngine({
      'INP_DFMSPH22.c': cInputText,
      'INP_NN_forces.c': generateNNForcesFile(),
      'inp_rhoP.c': generateDensityFile(input.proj, input.dr_density, input.rMax_density),
      'inp_rhoT.c': generateDensityFile(input.targ, input.dr_density, input.rMax_density)
    });
  } catch (err: any) {
    return fallback(input, `[Execution Error] ${err?.message || String(err)}\nFalling back to TS engine.`);
  }
  const elapsed = Date.now() - t0;

  let logOutput = `=== DFMSPH22 Native C Execution Console (WebAssembly, ${elapsed} ms) ===\n`;
  logOutput += `=== C Program Stdout ===\n${run.stdout || '(No stdout output)'}\n`;

  if (run.exitCode !== 0) {
    return fallback(input, logOutput + `\n[Execution Error] Process exited with code ${run.exitCode}. Falling back to TS engine.`);
  }
  if (run.stdout.includes('ABNORMAL TERMINATION')) {
    logOutput += `\n[Warning] DFMSPH22 reported ABNORMAL TERMINATION (e.g. the R interval does not contain the barrier). Results below may be incomplete.`;
  }

  try {
    const outUR = run.files['OUT_U_R.c'] ?? '';
    const outDFM = run.files['out_dfmsph22.c'] ?? '';
    const outInp = run.files['out_inp_dfm22.c'] ?? '';

    let cOutputText = outUR;
    if (outDFM) cOutputText += '\n\n=== out_dfmsph22.c ===\n' + outDFM;
    if (outInp) cOutputText += '\n\n=== out_inp_dfm22.c ===\n' + outInp;

    /* Parse the summary line written by FUN_DFPOUT() to out_dfmsph22.c:
     * NUM Title(70 chars)<key>  <ver 22> ZP AP RP0 ZT AT RT0 r_bar BfusDFPsph Hom BZ rat_r rat_B C2b C3b
     *   i1chi2 VWSmem rWSmem aWSmem chi2WSmin A0 A1 A2 r0GK aGK chi2GKmin ECM key_exc key_vNN key_DD key_UC ...
     */
    let native_r_bar: number | null = null;
    let native_Bfus: number | null = null;
    let native_Hom: number | null = null;
    let native_VWSmem: number | null = null;
    let native_rWSmem: number | null = null;
    let native_aWSmem: number | null = null;
    let native_chi2WS: number | null = null;

    const summaryLine = outDFM.split('\n').find(l => l.includes('<ver'));
    if (summaryLine) {
      const afterVer = summaryLine.slice(summaryLine.indexOf('>', summaryLine.indexOf('<ver')) + 1);
      const nums = afterVer.trim().split(/\s+/).map(Number);
      if (nums.length >= 19 && nums[0] === input.proj.Z && nums[1] === input.proj.A && nums[3] === input.targ.Z && nums[4] === input.targ.A) {
        native_r_bar = nums[6];
        native_Bfus = nums[7];
        native_Hom = nums[8];
        native_VWSmem = nums[15];
        native_rWSmem = nums[16];
        native_aWSmem = nums[17];
        native_chi2WS = nums[18];
      }
    }

    /* Radial table from OUT_U_R.c: RCM UN UC Utot UNWSfit UNGKfit */
    const A_proj = input.proj.A;
    const A_targ = input.targ.A;
    const muAmu = (A_proj * A_targ) / (A_proj + A_targ);
    const hbar2_2mu = 20.73553 / muAmu;
    const wsValid = native_VWSmem !== null && native_VWSmem > -10000 && native_rWSmem !== null && native_rWSmem < 10;

    const radialData: RadialPoint[] = [];
    for (const line of outUR.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('RCM')) continue;
      if (trimmed.startsWith('<')) break; /* FUN_SEAL trailer */
      const parts = trimmed.split(/\s+/).map(Number);
      if (parts.length < 5 || parts.some(n => isNaN(n))) continue;

      const [R, V_df, V_c, V_tot_c, V_ws_nuclear] = parts;
      const V_cent = R > 0 ? (hbar2_2mu * input.Lwave * (input.Lwave + 1)) / (R * R) : 0;
      radialData.push({
        R: parseFloat(R.toFixed(3)),
        V_df: parseFloat(V_df.toFixed(4)),
        V_c: parseFloat(V_c.toFixed(4)),
        V_cent: parseFloat(V_cent.toFixed(4)),
        V_tot: parseFloat((V_tot_c + V_cent).toFixed(4)),
        V_ws: parseFloat(((wsValid ? V_ws_nuclear : V_df) + V_c).toFixed(4))
      });
    }
    /* C scans from large R to small R; plots expect ascending R */
    radialData.sort((a, b) => a.R - b.R);

    if (radialData.length === 0) {
      return fallback(input, logOutput + '\n[Parse Notice] Could not parse OUT_U_R.c radial points. Used TS engine fallback.');
    }

    /* Barrier: native value when found, otherwise the maximum of V_tot (s-wave value + centrifugal) */
    let V_b = -Infinity;
    let R_b = 0;
    if (native_Bfus !== null && native_r_bar !== null && native_r_bar > 0 && input.Lwave === 0) {
      V_b = native_Bfus;
      R_b = native_r_bar;
    } else {
      for (let i = 1; i < radialData.length - 1; i++) {
        const p = radialData[i];
        if (p.V_tot > radialData[i - 1].V_tot && p.V_tot >= radialData[i + 1].V_tot && p.V_tot > V_b) {
          V_b = p.V_tot;
          R_b = p.R;
        }
      }
      if (!isFinite(V_b)) {
        radialData.forEach(p => { if (p.V_tot > V_b) { V_b = p.V_tot; R_b = p.R; } });
      }
    }

    /* Curvature hbar*omega: native value (parabolic fit in FUN_Hom) or finite differences */
    let hbar_omega = native_Hom !== null && native_Hom > 0 && input.Lwave === 0 ? native_Hom : NaN;
    if (!(hbar_omega > 0)) {
      const idx = radialData.findIndex(p => Math.abs(p.R - R_b) < 1e-6);
      if (idx > 0 && idx < radialData.length - 1) {
        const dR = radialData[idx + 1].R - radialData[idx].R;
        const d2V = (radialData[idx + 1].V_tot - 2 * radialData[idx].V_tot + radialData[idx - 1].V_tot) / (dR * dR);
        hbar_omega = Math.sqrt(2 * hbar2_2mu * Math.abs(d2V));
      }
      if (!(hbar_omega > 0)) hbar_omega = 4.2;
    }

    /* Woods-Saxon fitted parameters (FUN_WS_DFP) */
    const A_sum_13 = Math.pow(A_proj, 1 / 3) + Math.pow(A_targ, 1 / 3);
    const V0_ws = wsValid ? Math.abs(native_VWSmem as number) : 0;
    const r0_param = wsValid ? (native_rWSmem as number) : 0;
    const a_ws = wsValid && native_aWSmem !== null ? native_aWSmem : 0;
    const rms_fit = wsValid && native_chi2WS !== null ? native_chi2WS : 0;

    const barrier: BarrierResult = {
      V_b: parseFloat(V_b.toFixed(3)),
      R_b: parseFloat(R_b.toFixed(3)),
      hbar_omega: parseFloat(hbar_omega.toFixed(3)),
      V0_ws: parseFloat(V0_ws.toFixed(3)),
      R0_ws: parseFloat((r0_param * A_sum_13).toFixed(3)),
      a_ws: parseFloat(a_ws.toFixed(3)),
      rms_fit: parseFloat(rms_fit.toExponential(2))
    };

    /* Fusion cross sections via Wong formula */
    const E_cm = input.energyLab * (input.targ.A / (input.proj.A + input.targ.A));
    const fusionData: FusionCrossSectionPoint[] = [];
    const eMin = Math.max(5, V_b - 25);
    const eMax = V_b + 45;
    const numE = 30;
    const stepE = (eMax - eMin) / numE;

    for (let i = 0; i <= numE; i++) {
      const E = eMin + i * stepE;
      const arg = (2 * Math.PI * (E - V_b)) / hbar_omega;
      const P = 1.0 / (1.0 + Math.exp(-arg));
      /* ln(1+e^x) evaluated stably */
      const softplus = arg > 30 ? arg : Math.log1p(Math.exp(arg));
      const sigmaMb = (hbar_omega * R_b * R_b / (2 * E)) * softplus * 10;

      fusionData.push({
        E_cm: parseFloat(E.toFixed(2)),
        crossSectionMb: parseFloat(Math.max(0, sigmaMb).toFixed(2)),
        penetrability: parseFloat(P.toFixed(6))
      });
    }

    /* Density profile points (the same densities that were written to inp_rhoP.c / inp_rhoT.c) */
    const densityData: DensityPoint[] = [];
    const normP = getDensityNormFactor(input.proj);
    const normT = getDensityNormFactor(input.targ);
    for (let ir = 0; ir <= 50; ir++) {
      const r = ir * 0.3;
      densityData.push({
        r: parseFloat(r.toFixed(2)),
        rho_proj: parseFloat((normP * calculateNuclearDensity(input.proj, r)).toFixed(6)),
        rho_targ: parseFloat((normT * calculateNuclearDensity(input.targ, r)).toFixed(6))
      });
    }

    logOutput += `\n[Native C Execution Successful] DFMSPH22 C code executed (compiled to WebAssembly).\nExtracted Parameters: V_b = ${barrier.V_b} MeV, R_b = ${barrier.R_b} fm, hbar_omega = ${barrier.hbar_omega} MeV, V0_ws = ${barrier.V0_ws} MeV, R0_ws = ${barrier.R0_ws} fm, a_ws = ${barrier.a_ws} fm.`;

    const resultOutput: CalculationOutput = {
      systemName: `${input.proj.name} + ${input.targ.name}`,
      E_cm: parseFloat(E_cm.toFixed(2)),
      reducedMassAmu: parseFloat(muAmu.toFixed(4)),
      barrier,
      radialData,
      densityData,
      fusionData,
      cInputText,
      cOutputText,
      cLogText: logOutput,
      isNativeExecution: true
    };

    return { output: resultOutput, isNative: true, log: logOutput };
  } catch (err: any) {
    return fallback(input, logOutput + `\n[Parse Error] Failed parsing C output files: ${err.message}. Falling back to TS engine.`);
  }
}

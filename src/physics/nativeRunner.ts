/*
 * Native C Runner for DFMSPH22
 * The original C sources (dfmsph22.c + modules) are compiled to WebAssembly (engine/dfmsph22.wasm,
 * see scripts/build-engine.mjs) and executed through Node's built-in WASI runtime. This works on
 * serverless hosts such as Vercel, where there is no gcc and the deployment directory is read-only:
 * every run gets its own temporary directory holding INP_DFMSPH22.c, INP_NN_forces.c, inp_rhoP.c,
 * inp_rhoT.c, and the program writes OUT_U_R.c / out_dfmsph22.c / out_inp_dfm22.c next to them.
 */

const WASM_PATH = path.join(process.cwd(), 'engine', 'dfmsph22.wasm');
const IRHOUP = 1000; /* dimension of the density tables in dfmsph_def.h */

let wasmModulePromise: Promise<WebAssembly.Module> | null = null;

export function isNativeEngineAvailable(): boolean {
  return fs.existsSync(WASM_PATH);
}

function getWasmModule(): Promise<WebAssembly.Module> {
  if (!wasmModulePromise) {
    wasmModulePromise = WebAssembly.compile(fs.readFileSync(WASM_PATH));
    wasmModulePromise.catch(() => { wasmModulePromise = null; });
  }
  return wasmModulePromise;
}

function generateDensityFile(nuc: NucleusConfig, dr_input?: number, rMax_input?: number): string {
  const normFactor = getDensityNormFactor(nuc);
  const dr = dr_input && dr_input > 0 ? dr_input : 0.1;
  /* The density must reach Crup*R0 (~1.5*1.2*A^1/3 fm, ~10.7 fm for 208Pb) plus the 4-point interpolation stencil */
  const rMax = rMax_input && rMax_input > 0 ? rMax_input : 15.0;
  const numSteps = Math.min(Math.round(rMax / dr), IRHOUP - 1);

  let content = `==== Density file for ${nuc.name} (Z=${nuc.Z}, A=${nuc.A}) generated by DFMSPH22 PWA ====\n`;
  content += `${nuc.densityType} density: c=${nuc.c} a=${nuc.a} w=${nuc.w}\n`;
  content += `${nuc.Z.toFixed(1)} ${nuc.A.toFixed(1)} ${dr.toFixed(4)}\n`;
  content += `I     R        RHO-COUL      RHO-PROT      RHO-NEUT     RHO-MASS\n`;

  const protonRatio = nuc.Z / nuc.A;
  const neutronRatio = (nuc.A - nuc.Z) / nuc.A;

  for (let i = 0; i <= numSteps; i++) {
    const r = i * dr;
    const rho = normFactor * calculateNuclearDensity(nuc, r);
    const rho_p = protonRatio * rho;
    const rho_n = neutronRatio * rho;
    const rho_c = rho_p;

    const iStr = (i + 1).toString().padStart(5);
    const rStr = r.toFixed(3).padStart(6);
    const fmt = (v: number) => v.toExponential(10).toUpperCase().padStart(17);
    content += `${iStr}  ${rStr}   ${fmt(rho_c)}   ${fmt(rho_p)}   ${fmt(rho_n)}   ${fmt(rho)}\n`;
  }
  /* Data terminator expected by FUN_Read_rho() in dfmsph_inp.c (R column == 123456789) */
  content += `${numSteps + 2} 123456789 0.0000000000E+00 0.0000000000E+00 0.0000000000E+00 0.0000000000E+00\n`;
  return content;
}

/* key_vN / key_D as understood by FUN_INP() and FUN_DFP_NNforce_INI() */
function nnKeys(nnType: CalculationInput['nnType']): { key_vN: number; key_D: number } {
  switch (nnType) {
    case 'm3y_reid': return { key_vN: 0, key_D: 0 };
    case 'm3y_paris': return { key_vN: 1, key_D: 0 };
    case 'migdal': return { key_vN: 2, key_D: 0 };
    case 'ddm3y1': return { key_vN: 1, key_D: 1 };  /* CDDdim[1]: C=0.2963 alpha=3.7231 beta=3.7384 gamma=0 */
    case 'cdm3y6': return { key_vN: 1, key_D: 7 };  /* CDDdim[7]: C=0.2658 alpha=3.8033 beta=1.4099 gamma=4.0 */
    case 'rmf_nl1': return { key_vN: 11, key_D: 0 };
    case 'rmf_nl2': return { key_vN: 12, key_D: 0 };
    case 'rmf_nl3': return { key_vN: 13, key_D: 0 };
    case 'rmf_tm1': return { key_vN: 21, key_D: 0 };
    default: return { key_vN: 1, key_D: 0 };
  }
}

function generateInputDFMSPH22(input: CalculationInput): string {
  const { proj, targ, nnType, energyLab, Rmin, Rmax, Rstep } = input;
  const E_cm = energyLab * (targ.A / (proj.A + targ.A));
  const { key_vN, key_D } = nnKeys(nnType);

  const r00 = input.r00 ?? 1.2;
  const key_ex = input.key_ex ?? 1;
  const key_C = input.key_C ?? 1;
  const k_up = input.k_up ?? 3.0;
  const Crup = input.Crup ?? 1.5;
  const eps_iter = input.eps_iter ?? 0.0001;
  const iter_up = input.iter_up ?? 30;

  /* The C code scans from RCCstart downwards to RCCfin */
  const startR = Math.max(Rmax, Rmin);
  const finR = Math.min(Rmax, Rmin);

  /* FUN_Hom fits U(R) on i_bar +/- iC2b grid points; keep that window near +/-1 fm whatever the step */
  const iC2b = Math.max(3, Math.round(1.0 / Rstep));

  const lines: string[] = [];
  lines.push(`${proj.name} + ${targ.name} System Input File for DFMSPH22`);
  lines.push(`ECM r00 iC2b`);
  lines.push(`${E_cm.toFixed(3)} ${r00.toFixed(2)} ${iC2b}`);
  lines.push(`ZP AP ZT AT`);
  lines.push(`${proj.Z.toFixed(1)} ${proj.A.toFixed(1)} ${targ.Z.toFixed(1)} ${targ.A.toFixed(1)}`);
  lines.push(`iter_up key_ex key_vN key_D key_C AdelCorr`);
  lines.push(`${Math.round(iter_up)} ${key_ex} ${key_vN} ${key_D} ${key_C} 0.0`);
  lines.push(`k_up Crup eps_iter RCCstart RCCfin RCCstep`);
  lines.push(`${k_up.toFixed(2)} ${Crup.toFixed(2)} ${eps_iter.toExponential(4)} ${startR.toFixed(2)} ${finR.toFixed(2)} ${Rstep.toFixed(3)}`);
  lines.push(`rWSmin rWSmax rWSstep VWSmin VWSmax VWSstep aWSmin aWSmax aWSstep chi2WS`);
  lines.push(`0.90 1.45 0.01 -400.0 -10.0 2.0 0.40 0.90 0.01 1.0`);
  lines.push(`fRBstart fRBfin deliR`);
  lines.push(`1.25 0.75 1`);
  lines.push(`rGKmin rGKmax rGKstep aGKmin aGKmax aGKstep`);
  lines.push(`1.0 1.4 0.05 0.5 0.8 0.05`);
  lines.push(`Amindim Amaxdim Astepdim chi2GK`);
  lines.push(`0.0 10.0 1.0 0.0 10.0 1.0 0.0 10.0 1.0 0.0`);

  return lines.join('\n') + '\n';
}

